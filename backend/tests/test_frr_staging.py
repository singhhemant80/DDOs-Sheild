# ---------------------------------------------------------------- the exit criterion
def test_authorised_host_route_reaches_lab_router_and_is_withdrawn(client, noc, lab):
    aid, c = run_active(client, noc)
    with session_factory()() as db:
        a = db.get(MitigationAction, uuid.UUID(aid))
        assert a.state == ActionState.ACTIVE and a.dry_run is False, (
            a.error + vtysh(PS_SHIELD, "show running-config") + vtysh(PS_SHIELD, "show bgp ipv4 unicast")
            + vtysh(PS_SHIELD, f"show bgp ipv4 unicast neighbors {LAB} advertised-routes"))
    routes = wait(lambda: lab_routes().get("163.5.191.20/32"))
    path = routes[0]
    assert path["nexthops"][0]["ip"] == "192.0.2.1"          # the lab filter's discard next hop
    full = json.loads(vtysh(PS_LAB, "show bgp ipv4 unicast 163.5.191.20/32 json"))
    comms = full["paths"][0]["community"]["list"]
    assert set(comms) == {"blackhole", "noExport"}           # FRR names 65535:666 "blackhole"
    # Shield accepts nothing back.
    assert "route-map SHIELD-DENY in" in vtysh(PS_SHIELD, "show running-config")

    client.post(f"{API}/actions/{aid}/withdraw", json={"reason": "lab done"}, headers=noc)
    c.tick()
    assert wait(lambda: "163.5.191.20/32" not in lab_routes())
    with session_factory()() as db:
        assert db.get(MitigationAction, uuid.UUID(aid)).state == ActionState.WITHDRAWN


def test_lab_router_rejects_unauthorised_routes_even_if_shield_sent_them(client, noc, lab):
    """Simulate a compromised or broken Shield: put routes straight into its FRR, bypassing every
    Shield check. The router's import filter (generated by Shield) still accepts only authorised /32s."""
    run_active(client, noc)
    assert wait(lambda: "163.5.191.20/32" in lab_routes())
    rogue = ["163.5.191.0/24", "163.5.191.0/25", "198.51.100.7/32"]
    vtysh(PS_SHIELD, *[f"ip prefix-list SHIELD4-int permit {p}" for p in rogue],
          f"router bgp {SHIELD_AS}", "address-family ipv4 unicast", *[f"network {p}" for p in rogue], configure=True)
    sent = wait(lambda: set(rogue) <= set(json.loads(vtysh(
        PS_SHIELD, f"show bgp ipv4 unicast neighbors {LAB} advertised-routes json"))["advertisedRoutes"]), 10)
    assert sent                                               # Shield did send them...
    time.sleep(2)
    got = set(lab_routes())
    assert got == {"163.5.191.20/32"}, got                    # ...the router kept only the authorised one
    # A protected /32 without the blackhole community is rejected too.
    vtysh(PS_SHIELD, "route-map SHIELD-OUT-int permit 10", "no set community", "exit",
          "ip prefix-list SHIELD4-int permit 163.5.191.21/32", f"router bgp {SHIELD_AS}",
          "address-family ipv4 unicast", "network 163.5.191.21/32", configure=True)
    vtysh(PS_SHIELD, f"clear bgp {LAB} soft out")
    time.sleep(2)
    assert "163.5.191.21/32" not in lab_routes()


