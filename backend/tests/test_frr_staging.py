def established(addr=LAB):
    return speaker().peer_state(addr) == "Established"


def propose_internal(client, h, target=VICTIM):
    r = client.post(f"{API}/actions", json={"target": target, "strategy": "rtbh_internal"},
                    headers={**h, "Idempotency-Key": uuid.uuid4().hex})
    return r


def run_active(client, noc, target=VICTIM):
    c = ctl()
    c.reconcile()                                     # configures the session
    assert wait(established), "session to the lab router did not come up"
    c.publish_status()
    r = propose_internal(client, noc, target)
    assert r.status_code == 201, r.text
    aid = r.json()["actions"][0]["id"]
    assert client.post(f"{API}/actions/{aid}/approve", headers=noc).status_code == 200
    c.tick()
    return aid, c


