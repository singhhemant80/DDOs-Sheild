def vtysh(ps, *lines, configure=False):
    argv = ["vtysh", "-N", ps] + (["-c", "configure terminal"] if configure else [])
    for line in lines:
        argv += ["-c", line]
    return subprocess.run(argv, capture_output=True, text=True, timeout=15).stdout


def start_bgpd(ps, listen, port, conf=""):
    for d in (f"/etc/frr/{ps}", f"/var/run/frr/{ps}"):
        os.makedirs(d, exist_ok=True)
        shutil.chown(d, "frr", "frr")
    path = f"/etc/frr/{ps}/frr.conf"
    with open(path, "w") as f:
        f.write("frr defaults traditional\nhostname " + ps + "\n" + conf)
    shutil.chown(path, "frr", "frr")
    subprocess.run(["pkill", "-f", f"bgpd -d -N {ps} "])
    time.sleep(0.3)
    subprocess.run([BGPD, "-d", "-N", ps, "-f", path, "-l", listen, "-p", str(port), "-Z",
                    "-i", f"/var/run/frr/{ps}/bgpd.pid"], check=True, capture_output=True)
    for _ in range(50):
        if "BGP" in vtysh(ps, "show bgp summary") or "No BGP" in vtysh(ps, "show bgp summary"):
            return
        time.sleep(0.1)


def stop_bgpd(ps):
    subprocess.run(["pkill", "-f", f"bgpd -d -N {ps} "])


