def test_upstream_route_carries_provider_communities(client, engineer, noc, admin, lab):
    uid = client.post("/api/v1/upstreams", json={"name": "Upstream-A", "asn": UP_AS}, headers=engineer).json()["id"]
    base = f"/api/v1/upstreams/{uid}/rtbh-policy"
