def _active_action(db_target=f"{VICTIM}/32"):
    with session_factory()() as db:
        return db.execute(select(MitigationAction).where(MitigationAction.state == ActionState.ACTIVE)).scalars().first()


@pytest.mark.parametrize("change,needle", [
    (dict(action_id=None), "valid action id"),
    (dict(action_id=str(uuid.uuid4())), "executing or active"),
    (dict(prefix="163.5.191.0/24"), "differs from its action"),
    (dict(prefix="163.5.191.20/32\nrouter bgp 1"), "malformed"),
    (dict(prefix="not-a-prefix"), "malformed"),
    (dict(communities=("65535:667",)), "policy changed"),
    (dict(peer="upstream:999"), "no Shield BGP session"),
])
def test_speaker_refuses_unauthorised_and_malformed(client, noc, lab, change, needle):
    run_active(client, noc)
    a = _active_action()
    base = dict(peer="internal", prefix=f"{VICTIM}/32", communities=("65535:666",), next_hop=None,
                no_export=True, action_id=str(a.id))
    before = vtysh(PS_SHIELD, "show running-config")
    with pytest.raises(SpeakerRefused) as e:
        speaker().announce(Route(**{**base, **change}))
    assert needle in str(e.value)
    after = vtysh(PS_SHIELD, "show running-config")
    assert before.split("!", 1)[1] == after.split("!", 1)[1]   # nothing changed in FRR


